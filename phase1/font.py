# font.py
#
# Port of ssd1306_font.h
# 8x5 font (5 columns, 8 rows per character).
# Each character is a tuple of 5 bytes; each byte is one column,
# LSB = top pixel row, MSB = bottom pixel row.
#
# Coverage: A-Z only.

CHARACTER_WIDTH = 5
CHARACTER_HEIGHT = 8

# fmt: off
FONT_A_Z = (
    (0x00, 0x7C, 0x12, 0x12, 0x7C),  # A
    (0x00, 0x7E, 0x4A, 0x4A, 0x34),  # B
    (0x00, 0x3C, 0x42, 0x42, 0x42),  # C
    (0x00, 0x7E, 0x42, 0x42, 0x3C),  # D
    (0x00, 0x7E, 0x4A, 0x4A, 0x42),  # E
    (0x00, 0x7E, 0x0A, 0x0A, 0x02),  # F
    (0x00, 0x3C, 0x42, 0x4A, 0x3A),  # G
    (0x00, 0x7E, 0x08, 0x08, 0x7E),  # H
    (0x00, 0x42, 0x7E, 0x42, 0x00),  # I
    (0x00, 0x22, 0x42, 0x42, 0x3E),  # J
    (0x00, 0x7E, 0x08, 0x14, 0x72),  # K
    (0x00, 0x7E, 0x40, 0x40, 0x40),  # L
    (0x7E, 0x04, 0x08, 0x04, 0x7E),  # M
    (0x00, 0x7E, 0x04, 0x08, 0x7E),  # N
    (0x00, 0x3C, 0x42, 0x42, 0x3C),  # O
    (0x00, 0x7E, 0x0A, 0x0A, 0x04),  # P
    (0x3E, 0x42, 0x62, 0x7E, 0x40),  # Q
    (0x00, 0x7E, 0x0A, 0x1A, 0x64),  # R
    (0x00, 0x44, 0x4A, 0x4A, 0x30),  # S
    (0x00, 0x02, 0x7E, 0x02, 0x00),  # T
    (0x00, 0x3E, 0x40, 0x40, 0x3E),  # U
    (0x00, 0x3E, 0x40, 0x3E, 0x00),  # V
    (0x3E, 0x40, 0x3C, 0x40, 0x3E),  # W
    (0x00, 0x76, 0x08, 0x76, 0x00),  # X
    (0x00, 0x0E, 0x70, 0x0E, 0x00),  # Y
    (0x00, 0x62, 0x52, 0x4A, 0x46),  # Z
)

def get_character(c: str) -> tuple | None:
    """Return the 5-byte column tuple for an uppercase letter or space, or None if not in the font."""
    if "A" <= c.upper() <= "Z":
        code = ord(c.upper()) - ord("A")
        return FONT_A_Z[code]
    elif c == " ":
        return (0x00, 0x00, 0x00, 0x00, 0x00)  # Space glyph (5 empty columns)
    return None
